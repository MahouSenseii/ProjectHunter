"""Restyle the existing ProjectHunter menu through Unreal's supported editor API.

Run with Unreal's Python plugin, never with the system Python interpreter.
Default: exercise the edits in memory without saving. Pass --apply to back up,
check Blueprint contracts, compile, and save only the eleven allowlisted menus.
Use -ExecutePythonScript (initialized editor/Slate), not -run=pythonscript.
Close other editors of this project before running a separate editor to save assets.
This script does not create widgets, edit graphs, or modify the player HUD.
"""

